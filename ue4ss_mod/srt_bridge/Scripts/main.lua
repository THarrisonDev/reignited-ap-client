-- SRTAP bridge: the in-game Archipelago client. This file is the boot and the
-- host API: it wires the parts (checkd, ap_client, session, watch), loads the
-- modules listed in modules.lua and hands each one the HOST capabilities it
-- needs. Per-part detail lives in those files; see docs/mod_architecture.md,
-- docs/game_gates.md and docs/game_state_control.md.

-- Scripts/ on package.path before the first require.
do
  local src = debug and debug.getinfo and debug.getinfo(1, "S")
  local dir = src and src.source and src.source:match("^@(.*[/\\])")
  if dir then
    package.path = package.path .. ";" .. dir .. "?.lua"
  end
end
local L = require("logger")
local log_info, log_error, log_debug = L.log_info, L.log_error, L.log_debug
local CFG = L.cfg
local BRIDGE_DIR = L.bridge_dir

--- Require a core module, logging FATAL and returning nil when it is unusable.
--- @param name string Require name.
--- @param what string Human label for the FATAL line.
--- @return table|nil
local function require_core(name, what)
  local ok, mod = pcall(require, name)
  if ok and type(mod) == "table" then
    return mod
  end
  log_error("FATAL: " .. what .. ": require('" .. name .. "') failed (" ..
    tostring(mod) .. ") — bridge stays offline")
  return nil
end

-- session_gate.lua is core like lua-apclientpp: a load failure is fatal and
-- stops the mod before any module or LoopAsync is wired.
local SESSION = require_core("session_gate", "session gate")
if not SESSION then return end
SESSION.init({})

-- The module inventory is core too: without it there is nothing to drive.
local MODULES = require_core("modules", "module inventory")
if not MODULES then return end

local state = require("state")
local checkd = require("checkd")
local ap_client = require("ap_client")
local session = require("session")
local watch = require("watch")
if not ap_client.available then
  log_error("FATAL: lua-apclientpp not loadable: " .. tostring(ap_client.load_error))
  return
end

state.reset()
-- A session file left by a crashed run would point checkd at the wrong save.
checkd.clear_session_file()

-- ---------------------------------------------------------------------------
-- Host capabilities
-- ---------------------------------------------------------------------------
-- Level path -> region name, generated by scripts/gen_locations.py from the
-- apworld's Locations.py and level_paths.py; never hand-edit (audit guards
-- drift).
local REGIONS = session.load_regions()

--- Return the location id for a fully-qualified name from slot_data.
--- @return number|nil
local function loc_id(name)
  return state.name_to_id[name]
end

-- The one per-poll game snapshot: watch.lua refreshes it, every module's tick
-- reads the same table. See docs/mod_architecture.md §3.
state.world = require("game_state").new({ regions = REGIONS })

-- Everything a module may use. Built once here; every field reads live state (or
-- forwards to the part that owns it) at call time, so it is safe to hand out
-- before a session exists. Shared tables are handed over by reference, and the
-- server is reachable only through the AP handle.
local HOST = {
  -- Data and hooks (host-owned).
  regions = REGIONS,
  bridge_dir = BRIDGE_DIR,
  checks_path = checkd.checks_path,
  id_to_name = state.id_to_name,
  sent_checks = state.sent_checks,
  loc_id = loc_id,
  notice = function(text)
    state.each("note_system", text)
  end,
  process_item = function(name, index)
    state.fan_out(name, index)
  end,
  -- The AP seam (ap_client.lua).
  ap = ap_client.handle,
}

-- ---------------------------------------------------------------------------
-- Module loading
-- ---------------------------------------------------------------------------
--- Build the inert stand-in for a module that failed to load: every method
--- answers (no-op, typed default), so the host's calls stay safe and a value
--- read gets 0/false rather than nil.
--- @return table
local function make_stub()
  return setmetatable({}, {
    __index = function(_, key)
      return function()
        if key == "received" then
          return 0
        end
        if key == "status" then
          return "unavailable"
        end
        return nil
      end
    end,
  })
end

--- Load one inventory entry: require it, build its init opts from HOST and init
--- it. Any failure is one ERROR line and an inert stand-in, never a dead bridge.
--- @return table Module, or an inert stand-in on failure.
--- @return string Heartbeat tag.
local function load_entry(entry)
  local ok, mod = pcall(require, entry.name)
  if not ok or type(mod) ~= "table" then
    log_error(entry.name .. ": require failed (" .. tostring(mod) .. ") — unavailable")
    return make_stub(), "[" .. entry.name .. "]"
  end
  local okO, opts = pcall(entry.opts, HOST)
  if not okO then
    log_error(entry.name .. ": init opts failed (" .. tostring(opts) .. ") — unavailable")
    return make_stub(), "[" .. entry.name .. "]"
  end
  local okI, err = pcall(mod.init, opts)
  if not okI then
    log_error(entry.name .. ": init failed (" .. tostring(err) .. ") — unavailable")
    return make_stub(), "[" .. entry.name .. "]"
  end
  return mod, type(mod.tag) == "string" and mod.tag or ("[" .. entry.name .. "]")
end

for _, entry in ipairs(MODULES) do
  entry.mod, entry.tag = load_entry(entry)
  state.mods[#state.mods + 1] = entry
  state.by_name[entry.name] = entry
end

-- Per-session watcher lists and the reconcile set, from the loaded inventory.
state.derive()

-- ---------------------------------------------------------------------------
-- Start
-- ---------------------------------------------------------------------------
watch.start()

log_debug("srt_bridge armed (host=" .. CFG.host .. " slot=" .. CFG.slot .. ")")
log_info("Pick New Game or Continue to connect to " .. CFG.host)
